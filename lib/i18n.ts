/** Kiểu nội dung dịch — tạo type mạnh từ nhánh "en". */
export type Messages = (typeof translations)["en"];

type RecursiveKeyOf<Obj extends object> = {
  [K in keyof Obj & string]: Obj[K] extends string
    ? K
    : Obj[K] extends object
      ? `${K}.${RecursiveKeyOf<Obj[K]>}`
      : never;
}[keyof Obj & string];

/** Key nội dung theo đường dẫn, ví dụ: "nav.home", "home.serviceExam". */
export type MessageKey = RecursiveKeyOf<Messages>;

/** Bỏ qua prefix để không vô tình dịch nhầm brand name. */
export const BRAND_RE = /belwee/i;

/** Giá trị ngôn ngữ hợp lệ cho localStorage. */
export function isLanguage(value: string | null | undefined): value is Language {
  return value === "en" || value === "vi";
}

/** Đọc ngôn ngữ đã lưu (localStorage) — an toàn khi gọi từ client. */
export function getStoredLanguage(): Language | null {
  if (typeof window === "undefined") return null;
  const saved = window.localStorage.getItem(LANG_KEY);
  return isLanguage(saved) ? saved : null;
}

/** Phát hiện ngôn ngữ trình duyệt: ưu tiên `navigator.languages`, dựa `navigator.language`. */
export function detectBrowserLanguage(): Language {
  if (typeof navigator !== "undefined") {
    const langs = (navigator.languages?.length ? navigator.languages : [navigator.language]).map(
      (l) => (l || "").toLowerCase()
    );
    if (langs.some((l) => l.startsWith("vi"))) return "vi";
    if (langs.some((l) => l.startsWith("en"))) return "en";
  }
  return "en";
}

/**
 * Ngôn ngữ mặc định khi vào website:
 * 1. Lựa chọn đã lưu (localStorage) — người dùng không phải chọn lại.
 * 2. Ngôn ngữ trình duyệt (`navigator.language`).
 * 3. Mặc định "en".
 * Không dùng IP, không ghi đè lựa chọn thủ công.
 */
export function getInitialLanguage(): Language {
  return getStoredLanguage() ?? detectBrowserLanguage();
}

/**
 * Tra cứu nội dung theo ngôn ngữ — hỗ trợ đường dẫn lồng nhau ("nav.home").
 *
 * `vars` (GĐ5) thay các placeholder `{tên}` trong chuỗi. Cần thiết vì thứ tự từ
 * của tiếng Việt và tiếng Anh khác nhau: "3,2 km" có thể đứng trước hoặc sau tên
 * chi nhánh, nên không thể ghép câu bằng cách cộng chuỗi ở component.
 *
 * Thay đổi này CỐ Ý không phá gì: không truyền `vars` thì hàm trả về đúng như
 * trước, vì `.replace` chỉ chạy khi có `vars`.
 */
export function translate(
  lang: Language,
  key: MessageKey,
  vars?: Record<string, string | number>
): string {
  const messages = translations[lang] as unknown as Record<string, unknown>;
  let current: unknown = messages;
  for (const part of key.split(".")) {
    if (typeof current !== "object" || current === null) return "";
    current = (current as Record<string, unknown>)[part];
  }
  if (typeof current !== "string") return "";
  if (!vars) return current;
  return current.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole
  );
}

